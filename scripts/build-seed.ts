/**
 * Generates supabase/seed.sql from supabase/data/accra-dodowa.json.
 * Idempotent: safe to run against a database that already has the seed.
 *
 *   node scripts/build-seed.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

type Stop = { idx: number; name: string; latitude: number; longitude: number; distance_m: number };
type Data = {
  route: { code: string; name: string; length_m: number; free_flow_s: number };
  stops: Stop[];
  path: { latitude: number; longitude: number }[];
};

const data = JSON.parse(readFileSync(new URL('../supabase/data/accra-dodowa.json', import.meta.url), 'utf8')) as Data;
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

// ── Seat layout: Toyota Coaster, 29 bookable seats (approved 2026-10-13) ──────────
// Left-hand drive, door front-right. Rows 1–6: 2 + aisle + 2. Back row: 5 (27 is the aisle seat).
type Cell = { type: 'seat'; no: number } | { type: 'aisle' | 'driver' | 'door' | 'empty' };
const seat = (no: number): Cell => ({ type: 'seat', no });
const grid: Cell[][] = [
  [{ type: 'driver' }, { type: 'empty' }, { type: 'aisle' }, { type: 'empty' }, { type: 'door' }],
  ...Array.from({ length: 6 }, (_, r): Cell[] => {
    const n = r * 4;
    return [seat(n + 1), seat(n + 2), { type: 'aisle' }, seat(n + 3), seat(n + 4)];
  }),
  [seat(25), seat(26), seat(27), seat(28), seat(29)],
];
const seatCount = grid.flat().filter((c) => c.type === 'seat').length;

// ── Routes: outbound in data order, inbound reversed and re-indexed ────────────────
const L = data.route.length_m;
const outbound = data.stops.map((s) => ({ name: s.name, idx: s.idx, distance_m: s.distance_m }));
const inbound = [...data.stops].reverse().map((s, i) => ({ name: s.name, idx: i, distance_m: L - s.distance_m }));

const routeSql = (direction: 'outbound' | 'inbound', name: string, stops: typeof outbound, path: Data['path']) => `
insert into public.routes (code, name, direction, length_m, free_flow_s)
values (${q(data.route.code)}, ${q(name)}, '${direction}', ${L}, ${data.route.free_flow_s})
on conflict (code, direction) do update
  set name = excluded.name, length_m = excluded.length_m, free_flow_s = excluded.free_flow_s;

insert into public.route_stops (route_id, stop_idx, stop_id, distance_m)
select r.id, v.idx, s.id, v.distance_m
from (values
${stops.map((s) => `  (${s.idx}, ${q(s.name)}, ${s.distance_m})`).join(',\n')}
) as v (idx, name, distance_m)
join public.stops s on s.name = v.name
join public.routes r on r.code = ${q(data.route.code)} and r.direction = '${direction}'
on conflict (route_id, stop_idx) do update set stop_id = excluded.stop_id, distance_m = excluded.distance_m;

insert into public.route_paths (route_id, path)
select r.id, ${json(path)}
from public.routes r where r.code = ${q(data.route.code)} and r.direction = '${direction}'
on conflict (route_id) do update set path = excluded.path;
`;

// ── Trips: PLACEHOLDER schedule (not in the docs) for the current day, Africa/Accra ──
const trips: { plate: string; direction: 'inbound' | 'outbound'; time: string }[] = [
  { plate: 'GLYDE-TEST-01', direction: 'inbound', time: '06:00' },
  { plate: 'GLYDE-TEST-02', direction: 'inbound', time: '06:30' },
  { plate: 'GLYDE-TEST-01', direction: 'outbound', time: '17:00' },
  { plate: 'GLYDE-TEST-02', direction: 'outbound', time: '17:30' },
];

const sql = `-- GENERATED by scripts/build-seed.ts from supabase/data/accra-dodowa.json — do not edit by hand.
-- ${data.stops.length} stops, ${(L / 1000).toFixed(1)} km. Test fleet and trip times are placeholders.

insert into public.stops (name, latitude, longitude) values
${data.stops.map((s) => `  (${q(s.name)}, ${s.latitude}, ${s.longitude})`).join(',\n')}
on conflict (name) do update set latitude = excluded.latitude, longitude = excluded.longitude;
${routeSql('outbound', `${data.route.name}`, outbound, data.path)}${routeSql('inbound', 'Dodowa – Accra', inbound, [...data.path].reverse())}
insert into public.seat_layouts (name, seat_count, grid)
values ('Toyota Coaster 29', ${seatCount}, ${json(grid)})
on conflict (name) do update set seat_count = excluded.seat_count, grid = excluded.grid;

-- Test fleet (fake plates).
insert into public.buses (plate, layout_id)
select v.plate, l.id from (values ('GLYDE-TEST-01'), ('GLYDE-TEST-02')) as v (plate)
join public.seat_layouts l on l.name = 'Toyota Coaster 29'
on conflict (plate) do nothing;

-- Placeholder trips for today (Africa/Accra). Re-run the seed on another day to get that day's trips.
insert into public.trips (route_id, bus_id, departs_at)
select r.id, b.id, ((now() at time zone 'Africa/Accra')::date + v.t::time) at time zone 'Africa/Accra'
from (values
${trips.map((t) => `  (${q(t.plate)}, '${t.direction}', '${t.time}')`).join(',\n')}
) as v (plate, direction, t)
join public.buses b on b.plate = v.plate
join public.routes r on r.code = ${q(data.route.code)} and r.direction = v.direction::public.route_direction
on conflict (bus_id, departs_at) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql: ${data.stops.length} stops × 2 directions, ${data.path.length} path points, layout ${seatCount} seats, ${trips.length} trips`);
